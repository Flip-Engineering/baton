async function correspondenceBytes(root) {
  const file = path.join(root, 'source-correspondence.json');
  const entries = readJson(file);
  if (!Array.isArray(entries)) throw new Error(`${file}: expected a JSON array`);
  const problems = [];
  const cache = new Map();
  const bytesOf = (target) => {
    if (!cache.has(target)) cache.set(target, readBytes(target));
    return cache.get(target);
  };
  const rows = [];

  entries.forEach((entry, index) => {
    const at = `source-correspondence.json[${index}]`;
    const original = bytesOf(entry.original);
    const generated = bytesOf(entry.generated);
    const originalDigest = sha256Hex(original);
    const generatedDigest = sha256Hex(generated);
    if (originalDigest !== entry.original_sha256) {
      problems.push(`${at}: ${entry.original} hashes to ${originalDigest}, recorded ${entry.original_sha256}`);
    }
    if (generatedDigest !== entry.generated_sha256) {
      problems.push(`${at}: ${entry.generated} hashes to ${generatedDigest}, recorded ${entry.generated_sha256}`);
    }
    const originalSpan = Array.isArray(entry.original_byte_span)
      ? { start: entry.original_byte_span[0], stop: entry.original_byte_span[1] }
      : null;
    const generatedSpan = Array.isArray(entry.generated_byte_span)
      ? { start: entry.generated_byte_span[0], stop: entry.generated_byte_span[1] }
      : null;
    if (!spanInBounds(original, originalSpan) || !spanInBounds(generated, generatedSpan)) {
      problems.push(
        `${at}: span out of range (original ${JSON.stringify(entry.original_byte_span)} of ${original.length} bytes, generated ${JSON.stringify(entry.generated_byte_span)} of ${generated.length} bytes)`,
      );
      return;
    }
    const originalSegment = original.subarray(originalSpan.start, originalSpan.stop);
    const generatedSegment = generated.subarray(generatedSpan.start, generatedSpan.stop);
    const identical = originalSegment.equals(generatedSegment);
    const segmentDigest = sha256Hex(generatedSegment);
    if (!identical) {
      problems.push(
        `${at}: original span ${originalSpan.start}..${originalSpan.stop} differs from generated span ${generatedSpan.start}..${generatedSpan.stop}`,
      );
    }
    if (segmentDigest !== entry.segment_sha256) {
      problems.push(`${at}: segment hashes to ${segmentDigest}, recorded ${entry.segment_sha256}`);
    }
    if (identical !== entry.identical_bytes) {
      problems.push(`${at}: identical_bytes is ${entry.identical_bytes} while the byte comparison is ${identical}`);
    }
    rows.push({
      index,
      original: entry.original,
      generated: entry.generated,
      original_span: [originalSpan.start, originalSpan.stop],
      generated_span: [generatedSpan.start, generatedSpan.stop],
      segment_bytes: generatedSpan.stop - generatedSpan.start,
      identical_bytes: identical,
      segment_sha256: segmentDigest,
    });
  });

  const ok = problems.length === 0;
  const summary = `${rows.length} of ${entries.length} correspondence entries recomputed (file digests, span bounds, byte equality, segment digests, identical_bytes)`;
  return { ok, detail: withProblems(summary, problems), evidence: { file, entries: entries.length, rows } };
}

