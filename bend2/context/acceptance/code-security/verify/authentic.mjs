async function compilerIdentities(root, options) {
  const identitiesFile = path.join(root, 'compiler/tool-identities.json');
  const commandsFile = path.join(root, 'compiler/commands.json');
  const versionsFile = path.join(root, 'compiler/tool-versions.txt');
  const identities = readJson(identitiesFile);
  const commands = readJson(commandsFile);
  const versionsText = readText(versionsFile);
  if (!Array.isArray(identities)) throw new Error(`${identitiesFile}: expected a JSON array`);
  if (!Array.isArray(commands)) throw new Error(`${commandsFile}: expected a JSON array`);
  const clang = options.clang ?? DEFAULT_CLANG;
  const clangd = options.clangd ?? DEFAULT_CLANGD;
  const problems = [];
  const probes = new Map();
  const probe = (file) => {
    if (!probes.has(file)) probes.set(file, runCapture(file, ['--version']));
    return probes.get(file);
  };

  const recorded = [];
  for (const entry of identities) {
    const file = entry.path;
    if (typeof file !== 'string') {
      problems.push('tool-identities.json holds an entry without a path');
      continue;
    }
    if (!existsSync(file)) {
      problems.push(`${file}: recorded tool is absent`);
      continue;
    }
    const digest = sha256Hex(readBytes(file));
    if (digest !== entry.sha256) problems.push(`${file}: hashes to ${digest}, recorded ${entry.sha256}`);
    const row = { path: file, sha256: digest, recorded_sha256: entry.sha256, version: null };
    if ((statSync(file).mode & 0o111) !== 0) {
      const result = probe(file);
      const firstLine = result.stdout.split('\n')[0].trim();
      row.version = firstLine;
      if (result.status !== 0) problems.push(`${file} --version exits ${result.status}`);
      if (!result.stdout.includes('20.1.8')) problems.push(`${file} --version reports no 20.1.8`);
      if (firstLine.length > 0 && !versionsText.includes(firstLine)) {
        problems.push(`${file} --version first line ${JSON.stringify(firstLine)} is absent from compiler/tool-versions.txt`);
      }
    }
    recorded.push(row);
  }

  // Installed clang-20 and clangd named by the check contract.
  const installed = [];
  for (const [name, file] of [['clang-20', clang], ['clangd', clangd]]) {
    if (!existsSync(file)) {
      problems.push(`${name}: ${file} is absent`);
      continue;
    }
    const result = probe(file);
    const firstLine = result.stdout.split('\n')[0].trim();
    installed.push({ name, path: file, realpath: realpathSync(file), version: firstLine, digest: sha256Hex(readBytes(file)) });
    if (result.status !== 0) problems.push(`${file} --version exits ${result.status}`);
    if (!result.stdout.includes('20.1.8')) problems.push(`${file} --version does not report 20.1.8`);
  }

  const installedClang = installed.find((entry) => entry.name === 'clang-20');
  const clangIdentity = recorded.find((entry) => path.basename(entry.path).startsWith('clang'));
  if (installedClang && clangIdentity) {
    if (realpathSync(clangIdentity.path) !== installedClang.realpath) {
      problems.push(
        `recorded clang identity ${clangIdentity.path} resolves to ${realpathSync(clangIdentity.path)} while ${installedClang.path} resolves to ${installedClang.realpath}`,
      );
    }
  }
  const recordedClangd = recorded.find((entry) => path.basename(entry.path).startsWith('clangd'));
  const clangdCovers = installed.find((entry) => entry.name === 'clangd');
  if (clangdCovers && recordedClangd === undefined) {
    // The record carries no clangd digest; the version probe below is the only
    // clangd identity available from the retained files.
    clangdCovers.no_recorded_digest = true;
  }

  // tool-versions.txt equals the clang-20 probe output followed by one LLVM tool
  // probe output.
  const normalize = (text) => text.replace(/[ \t]+$/gm, '').replace(/\n+$/, '\n');
  const clangVersionText = installedClang ? probe(installedClang.path).stdout : null;
  const versionSources = [];
  let versionsMatch = null;
  if (clangVersionText !== null) {
    for (const row of recorded) {
      if (row.version === null || !/LLVM version/.test(row.version)) continue;
      const combined = normalize(clangVersionText + probe(row.path).stdout);
      versionSources.push({ with: row.path, matches: combined === normalize(versionsText) });
      if (combined === normalize(versionsText)) versionsMatch = row.path;
    }
  }
  if (clangVersionText !== null && versionsMatch === null) {
    problems.push(
      `compiler/tool-versions.txt does not equal the clang-20 probe output followed by a recorded LLVM tool probe output (tried ${versionSources.length} tools)`,
    );
  }

  // Every recorded command names an executable that reports this front end and
  // carries return code 0.
  const commandsChecked = [];
  commands.forEach((command, index) => {
    const argv = Array.isArray(command.argv) ? command.argv : [];
    const executable = argv[0];
    const at = `commands.json[${index}]`;
    if (typeof executable !== 'string' || executable.length === 0) {
      problems.push(`${at}: empty argv`);
      return;
    }
    if (!existsSync(executable)) {
      problems.push(`${at}: executable ${executable} is absent`);
      return;
    }
    const result = probe(executable);
    if (result.status !== 0) problems.push(`${at}: ${executable} --version exits ${result.status}`);
    if (!result.stdout.includes('20.1.8')) problems.push(`${at}: ${executable} front-end version does not resolve to 20.1.8`);
    if (command.returncode !== 0) problems.push(`${at}: recorded return code ${command.returncode}`);
    commandsChecked.push({ index, executable, returncode: command.returncode, version: result.stdout.split('\n')[0].trim() });
  });

  const ok = problems.length === 0;
  const summary = `${recorded.length} recorded tool identities recomputed; ${commandsChecked.length} compile commands name an executable reporting 20.1.8 with recorded return code 0; installed clang-20 and clangd probes resolve to 20.1.8`;
  return {
    ok,
    detail: withProblems(summary, problems),
    evidence: {
      identities: recorded,
      installed,
      versions_file: versionsFile,
      versions_match_tool: versionsMatch,
      tool_versions_lines: versionsText.split('\n').filter((line) => line.trim().length > 0),
      commands: commandsChecked,
    },
  };
}

