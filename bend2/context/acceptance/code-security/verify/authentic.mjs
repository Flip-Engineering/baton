const CHECKS = [
  ['correspondence-bytes', correspondenceBytes],
  ['manifest-digests', manifestDigests],
  ['compiler-identities', compilerIdentities],
  ['catalog-provenance', catalogProvenance],
  ['guard-span', guardSpan],
  ['relation-recompute', relationRecompute],
  ['same-handler-families', sameHandlerFamilies],
  ['database-join', databaseJoin],
  ['claim-discipline', claimDiscipline],
  ['no-enforcement-claim', noEnforcementClaim],
];

export async function verifyAuthentic(evidenceRoot = DEFAULT_EVIDENCE_ROOT, options = {}) {
  if (typeof evidenceRoot !== 'string' || evidenceRoot.length === 0) {
    throw new Error('verifyAuthentic requires an evidence root path');
  }
  const root = path.resolve(evidenceRoot);
  if (!existsSync(root)) throw new Error(`evidence root is absent: ${root}`);
  const selected = Array.isArray(options.checks) && options.checks.length > 0 ? new Set(options.checks) : null;
  const checks = [];
  for (const [id, run] of CHECKS) {
    if (selected !== null && !selected.has(id)) continue;
    try {
      const outcome = await run(root, options);
      checks.push({ id, ok: outcome.ok === true, detail: String(outcome.detail ?? ''), evidence: outcome.evidence ?? null });
    } catch (error) {
      checks.push({ id, ok: false, detail: `check did not complete: ${error instanceof Error ? error.message : String(error)}`, evidence: null });
    }
  }
  return { checks, ok: checks.every((entry) => entry.ok) };
}

function invokedDirectly() {
  const entry = process.argv[1];
  if (!entry) return false;
  try {
    return realpathSync(entry) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (invokedDirectly()) {
  const root = process.argv[2] ?? DEFAULT_EVIDENCE_ROOT;
  verifyAuthentic(root)
    .then((result) => {
      process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
      process.exitCode = result.ok ? 0 : 1;
    })
    .catch((error) => {
      process.stderr.write(`verification did not run: ${error instanceof Error ? error.stack : String(error)}\n`);
      process.exitCode = 2;
    });
}
