function readBytes(file) {
  if (!existsSync(file)) throw new Error(`missing file: ${file}`);
  return readFileSync(file);
}

function readText(file) {
  return readBytes(file).toString('utf8');
}

function readJson(file) {
  const text = readText(file);
  try {
    return JSON.parse(text);
  } catch (error) {
    throw new Error(`invalid JSON in ${file}: ${error.message}`);
  }
}

function sha256Hex(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

function sha1Hex(bytes) {
  return createHash('sha1').update(bytes).digest('hex');
}

// Fossil artifact ids are SHA-1 (40 hex digits) or SHA3-256 (64 hex digits)
// according to the repository hash policy.
function fossilDigestHex(bytes, recorded) {
  if (/^[0-9a-f]{40}$/i.test(recorded)) return sha1Hex(bytes);
  if (/^[0-9a-f]{64}$/i.test(recorded)) return createHash('sha3-256').update(bytes).digest('hex');
  return null;
}

function runCapture(command, args) {
  const result = spawnSync(command, args, { encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 });
  if (result.error) throw new Error(`cannot run ${command}: ${result.error.message}`);
  return { status: result.status, stdout: result.stdout ?? '', stderr: result.stderr ?? '' };
}

// Recorded ranges use begin.offset and end.offset with the end token length, so
// the covered bytes are [begin.offset, end.offset + end.tokLen).
function spanOf(range) {
  const begin = range && range.begin;
  const end = range && range.end;
  if (!begin || !end) return null;
  const start = begin.offset;
  const stop = end.offset + (typeof end.tokLen === 'number' ? end.tokLen : 0);
  if (!Number.isInteger(start) || !Number.isInteger(stop)) return null;
  return { start, stop };
}

function spanText(bytes, span) {
  return bytes.subarray(span.start, span.stop).toString('utf8');
}

function spanInBounds(bytes, span) {
  return span !== null && span.start >= 0 && span.stop <= bytes.length && span.stop > span.start;
}

function reachable(successors, start, skippedEdges) {
  const seen = new Set();
  const queue = [start];
  while (queue.length > 0) {
    const node = queue.pop();
    if (seen.has(node)) continue;
    seen.add(node);
    for (const next of successors.get(node) ?? []) {
      if (skippedEdges && skippedEdges.has(`${node}->${next}`)) continue;
      queue.push(next);
    }
  }
  return [...seen].sort((left, right) => left - right);
}

function sameNumberSet(left, right) {
  if (!Array.isArray(left) || !Array.isArray(right)) return false;
  const a = [...new Set(left)].sort((x, y) => x - y);
  const b = [...new Set(right)].sort((x, y) => x - y);
  return a.length === b.length && a.every((value, index) => value === b[index]);
}

function formatProblems(problems, limit = 12) {
  const shown = problems.slice(0, limit).join(' | ');
  return problems.length > limit ? `${shown} | and ${problems.length - limit} more` : shown;
}

function withProblems(summary, problems) {
  if (problems.length === 0) return summary;
  return `${summary} Failures (${problems.length}): ${formatProblems(problems)}`;
}

function displayPath(root, file) {
  const relative = path.relative(root, file);
  return relative && !relative.startsWith('..') ? relative : file;
}

// Parse the DumpCFG text into blocks with ordered successors. A block header is
// a line such as " [B34 (ENTRY)]" or " [B1]". Body lines carry "Succs (n): ...",
// "Preds (n): ..." and the terminator line "T: ...".
function parseCfg(text) {
  const blocks = new Map();
  const header = /^ \[B(\d+)(?: \((\w+)\))?\]$/;
  let current = null;
  for (const line of text.split('\n')) {
    const match = header.exec(line);
    if (match) {
      current = {
        id: Number(match[1]),
        label: match[2] ?? null,
        successors: [],
        declaredSuccessorCount: null,
        hasConditionalTerminator: false,
        body: [],
      };
      blocks.set(current.id, current);
      continue;
    }
    if (current === null) continue;
    current.body.push(line);
    const successors = /^\s*Succs \((\d+)\):(.*)$/.exec(line);
    if (successors) {
      current.declaredSuccessorCount = Number(successors[1]);
      current.successors = [...successors[2].matchAll(/B(\d+)/g)].map((entry) => Number(entry[1]));
    }
    if (/^\s*T:/.test(line)) current.hasConditionalTerminator = true;
  }
  return blocks;
}

// Walk every object that carries a string `class` field: the graded blocks.
function gradedBlocks(value) {
  const found = [];
  const visit = (node, at) => {
    if (Array.isArray(node)) {
      node.forEach((child, index) => visit(child, `${at}[${index}]`));
      return;
    }
    if (node && typeof node === 'object') {
      if (typeof node.class === 'string') found.push({ at, block: node });
      for (const [key, child] of Object.entries(node)) visit(child, `${at}.${key}`);
    }
  };
  visit(value, '$');
  return found;
}

function collectStrings(value, at = '$', out = []) {
  if (typeof value === 'string') {
    out.push({ at, text: value });
    return out;
  }
  if (Array.isArray(value)) {
    value.forEach((child, index) => collectStrings(child, `${at}[${index}]`, out));
    return out;
  }
  if (value && typeof value === 'object') {
    for (const [key, child] of Object.entries(value)) collectStrings(child, `${at}.${key}`, out);
  }
  return out;
}

// Clause-level scan for positive claims about guard enforcement, principal
// authenticity or effect completion. A clause that carries a negation token is
// a limitation statement and is accepted.
const CLAIM_PATTERN =
  /\b(?:enforce|enforces|enforced|enforcement)\b|\bguarantee(?:s|d)?\b|\ball[- ]paths?\b|\buniversal(?:ly)?\b|\bprove(?:s|d)?\b|\bproofs?\b|\bauthenticate(?:s|d)?\b|\bauthenticated\b|\bauthentication\b|\bauthenticity\b|\btrusted (?:origin|identity|principal)\b/i;
const COMPLETION_PATTERN = /\bcomplet(?:e|es|ed|ion)\b/i;
const EFFECT_CONTEXT_PATTERN = /\b(?:effect|effects|call|calls|execution|executed|statement|statements)\b/i;
const NEGATION_PATTERN =
  /\b(?:no|not|never|none|without|cannot|absent|absence|unavailable|unverified|unsettled|unsupported|refused|refuses|incomplete|missing|partial|nor|neither)\b/i;

function enforcementClaims(text) {
  const clauses = String(text).split(/[.;\n]/);
  const hits = [];
  for (const clause of clauses) {
    const positive = CLAIM_PATTERN.test(clause) || (COMPLETION_PATTERN.test(clause) && EFFECT_CONTEXT_PATTERN.test(clause));
    if (!positive) continue;
    if (NEGATION_PATTERN.test(clause)) continue;
    hits.push(clause.trim());
  }
  return hits;
}

// Count the top-level arguments of a call whose text starts at the callee name.
// String and character literals are skipped so that commas inside the SQL
// literal do not count as argument separators.
function countCallArguments(callText) {
  let index = callText.indexOf('(');
  if (index < 0) return null;
  let depth = 0;
  let argumentCount = 1;
  let sawContent = false;
  let quote = null;
  for (; index < callText.length; index += 1) {
    const character = callText[index];
    if (quote !== null) {
      if (character === '\\') index += 1;
      else if (character === quote) quote = null;
      continue;
    }
    if (character === '"' || character === "'") {
      quote = character;
      sawContent = true;
      continue;
    }
    if (character === '(') depth += 1;
    else if (character === ')') {
      depth -= 1;
      if (depth === 0) return sawContent || argumentCount > 1 ? argumentCount : 0;
    } else if (character === ',' && depth === 1) argumentCount += 1;
    else if (!/\s/.test(character)) sawContent = true;
  }
  return null;
}

// Hash every regular file that is a direct child of `directories` and return the
// paths whose digest matches. The scan feeds the observed-block evidence lookup;
// its scope is the retained evidence neighborhood, not the whole probe tree.
function filesByDigest(root, digest, directories) {
  const matches = [];
  for (const directory of directories) {
    const absolute = path.join(root, directory);
    if (!existsSync(absolute)) continue;
    const stats = statSync(absolute);
    const names = stats.isDirectory() ? readdirSync(absolute) : [''];
    for (const name of names) {
      const file = name === '' ? absolute : path.join(absolute, name);
      let fileStats;
      try {
        fileStats = statSync(file);
      } catch {
        continue;
      }
      if (!fileStats.isFile() || fileStats.size > 256 * 1024 * 1024) continue;
      if (sha256Hex(readBytes(file)) === digest) matches.push(file);
    }
  }
  return matches;
}

