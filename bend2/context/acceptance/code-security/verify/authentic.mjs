// Read-only verification of the retained authentic Fossil qualification record.
//
// Every check recomputes its claim from the retained bytes and JSON documents
// under the evidence root: file and segment digests, byte spans, graded
// classification fields, CFG reachability, catalog rows and installed tool
// identities. No recorded number is taken as input to a result.
//
// The module opens every file read-only and writes nothing. The evidence root
// is a parameter; the default is the retained fossil-qualification probe tree.
//
// check ids and what each one recomputes:
//   correspondence-bytes   source-correspondence.json file and segment digests
//   manifest-digests       manifest-check.json entries against source/fossil/manifest
//   compiler-identities    compiler/tool-identities.json, tool-versions.txt, commands.json
//   catalog-provenance     catalog-plan.json against runtime-connection/allowed.fossil
//   guard-span             security.relation.guard and fields offsets in the generated bytes
//   relation-recompute     compiler/view-list-cfg.txt successor map and reachability
//   same-handler-families  the five graded families and the selected-parameter gate
//   database-join          database literal span, prepare call, statement declaration
//   claim-discipline       required fields per classification class in joined-result.json
//   no-enforcement-claim   enforcement, authenticity and completion assertions in strings

