async function manifestDigests(root) {
  const filesRoot = path.join(root, 'source/fossil');
  const manifestFile = path.join(filesRoot, 'manifest');
  const manifestBytes = readBytes(manifestFile);
  const manifestText = manifestBytes.toString('utf8');
  const check = readJson(path.join(root, 'manifest-check.json'));
  const problems = [];

  const cards = new Map();
  for (const line of manifestText.split('\n')) {
    if (!line.startsWith('F ')) continue;
    const parts = line.trim().split(/\s+/);
    if (parts.length >= 3) cards.set(parts[1], parts[2]);
  }

  const manifestDigest = sha1Hex(manifestBytes);
  const uuidFile = path.join(filesRoot, 'manifest.uuid');
  const recordedUuid = existsSync(uuidFile) ? readText(uuidFile).trim() : null;
  if (recordedUuid !== null && recordedUuid !== manifestDigest) {
    problems.push(`manifest.uuid records ${recordedUuid} while the manifest bytes hash to ${manifestDigest}`);
  }
  if (typeof check.full_identity === 'string' && check.full_identity !== manifestDigest) {
    problems.push(`manifest-check.json full_identity ${check.full_identity} differs from the manifest digest ${manifestDigest}`);
  }

  const entries = Array.isArray(check.files) ? check.files : [];
  const mismatched = [];
  const notRecomputed = [];
  const flagMismatch = [];
  let matched = 0;

  for (const entry of entries) {
    const name = entry.path;
    if (typeof name !== 'string' || name.length === 0) {
      problems.push('manifest-check.json holds an entry without a path');
      continue;
    }
    const target = path.resolve(filesRoot, name);
    if (target !== path.resolve(filesRoot) && !target.startsWith(`${path.resolve(filesRoot)}${path.sep}`)) {
      problems.push(`${name}: path leaves the source root`);
      continue;
    }
    const present = existsSync(target);
    if (!present) {
      notRecomputed.push(name);
      problems.push(`${name}: no file under ${filesRoot}`);
      continue;
    }
    if (entry.present !== true) flagMismatch.push(`${name}: present=${entry.present} while the file exists`);
    const recorded = cards.get(name);
    if (recorded === undefined) {
      notRecomputed.push(name);
      problems.push(`${name}: the retained manifest records no hash`);
      continue;
    }
    const digest = fossilDigestHex(readBytes(target), recorded);
    if (digest === null) {
      notRecomputed.push(name);
      problems.push(`${name}: recorded hash ${recorded} has no supported length`);
      continue;
    }
    const agrees = digest === recorded;
    if (agrees) matched += 1;
    else mismatched.push(`${name}: file hashes to ${digest}, manifest records ${recorded}`);
    if (entry.sha1_matches !== agrees) {
      flagMismatch.push(`${name}: sha1_matches=${entry.sha1_matches} while recomputation gives ${agrees}`);
    }
  }

  problems.push(...mismatched, ...flagMismatch);
  const recomputed = matched + mismatched.length;
  const ok = problems.length === 0 && recomputed === entries.length;
  const summary = `${recomputed} of ${entries.length} manifest entries recomputed against ${displayPath(root, manifestFile)} (${cards.size} F cards); manifest digest ${manifestDigest}`;
  return {
    ok,
    detail: withProblems(summary, problems),
    evidence: {
      manifest: manifestFile,
      manifest_sha1: manifestDigest,
      manifest_uuid: recordedUuid,
      full_identity: check.full_identity ?? null,
      f_card_count: cards.size,
      entries: entries.length,
      matched,
      mismatched,
      not_recomputed: notRecomputed,
    },
  };
}

