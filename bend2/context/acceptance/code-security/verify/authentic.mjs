// 9. claim-discipline
// ---------------------------------------------------------------------------

// Required field per classification class. Field names are matched
// case-insensitively as substrings; the semantic role comes from the class
// contract in the specification:
//   checked          an oracle verdict on a stated proposition
//   declared         an authored intent or external assumption with its source
//   observed         an actual observation with a retained evidence path
//   static-possible  a resolved static relation with its derivation or witness
const CLASS_FIELDS = {
  checked: [
    { role: 'oracle', match: (name) => /oracle|provider|engine|checker|compiler/i.test(name) },
    { role: 'proposition', match: (name) => /proposition|claim|verdict|statement|meaning/i.test(name) },
  ],
  declared: [{ role: 'author or authored source', match: (name) => /author|authority|authorship|source|document|declared/i.test(name) }],
  'static-possible': [{ role: 'derivation or witness', match: (name) => /derivation|provider|model|method|basis|scope|witness|raw|evidence|reference/i.test(name) }],
};

async function claimDiscipline(root) {
  const joinedFile = path.join(root, 'joined-result.json');
  const joined = readJson(joinedFile);
  const problems = [];
  const rows = [];

  const existingPaths = (block) => {
    const found = [];
    for (const [name, value] of Object.entries(block)) {
      if (typeof value !== 'string') continue;
      const candidates = path.isAbsolute(value) ? [value] : [path.resolve(root, value)];
      for (const candidate of candidates) {
        if (existsSync(candidate)) found.push({ field: name, path: candidate });
      }
    }
    return found;
  };

  for (const { at, block } of gradedBlocks(joined)) {
    const classification = block.class;
    const names = Object.keys(block);
    const satisfied = [];
    if (classification === 'observed') {
      const paths = existingPaths(block);
      if (paths.length === 0) problems.push(`${at} (class observed): missing an existing evidence path`);
      else satisfied.push(`evidence path via ${paths[0].field}`);
    } else {
      const requirements = CLASS_FIELDS[classification];
      if (requirements === undefined) {
        problems.push(`${at}: unknown class ${JSON.stringify(classification)}`);
        continue;
      }
      for (const requirement of requirements) {
        const hit = names.find((name) => requirement.match(name));
        if (hit === undefined) problems.push(`${at} (class ${classification}): missing ${requirement.role}`);
        else satisfied.push(`${requirement.role} via ${hit}`);
      }
    }
    if (classification === 'static-possible') {
      const hits = [];
      for (const { at: innerAt, text } of collectStrings(block, at)) {
        for (const claim of enforcementClaims(text)) hits.push(`${innerAt}: ${claim}`);
      }
      if (hits.length > 0) problems.push(`${at}: asserts enforcement, authenticity or completion (${hits.slice(0, 3).join(' | ')})`);
      else satisfied.push('no enforcement, authenticity or completion assertion');
    }
    rows.push({ at, class: classification, satisfied });
  }

  // Every runtime observation carries retained per-observation evidence, and
  // its recorded counts recompute from that evidence.
  const runtimeEvidence = [];
  const runtime = Array.isArray(joined.runtime) ? joined.runtime : [];
  const connections = Array.isArray(joined.runtime_connections) ? joined.runtime_connections : [];
  if (runtime.length === 0 && connections.length === 0) problems.push('joined-result.json records no runtime observation');
  const sql = joined.database?.sql;

  runtime.forEach((block, index) => {
    const at = `runtime[${index}]`;
    if (block.class !== 'observed') problems.push(`${at}: class ${block.class} in the runtime observation list`);
    const tracePath = block.sql_trace_path;
    if (typeof tracePath !== 'string' || !existsSync(tracePath)) {
      problems.push(`${at}: sql_trace_path ${JSON.stringify(tracePath)} is not a retained file`);
      return;
    }
    const traceLines = readText(tracePath).split('\n');
    const recomputedCount = traceLines.filter((line) => line.replace(/;\s*$/, '') === sql).length;
    if (recomputedCount !== block.sql_trace_exact_selected_count) {
      problems.push(
        `${at}: sql_trace_exact_selected_count is ${block.sql_trace_exact_selected_count} while ${displayPath(root, tracePath)} holds ${recomputedCount} exact statement lines`,
      );
    }
    const row = {
      at,
      context: block.context ?? null,
      trace: tracePath,
      trace_exact_selected_count: recomputedCount,
      coverage: null,
      digests: [],
    };
    const coveragePath = path.join(path.dirname(tracePath), `${block.context}-view_list-coverage.json`);
    if (existsSync(coveragePath)) {
      const coverage = readJson(coveragePath);
      if (coverage.count !== block.coverage_function_count) {
        problems.push(`${at}: coverage_function_count is ${block.coverage_function_count} while ${displayPath(root, coveragePath)} records ${coverage.count}`);
      }
      const branches = Array.isArray(coverage.branches) ? coverage.branches.slice(0, 2) : null;
      if (JSON.stringify(branches) !== JSON.stringify(block.guard_operand_branches)) {
        problems.push(`${at}: guard_operand_branches differ from the first two rows of ${displayPath(root, coveragePath)}`);
      }
      row.coverage = { path: coveragePath, count: coverage.count, branches_verified: true };
    } else {
      row.coverage = { path: coveragePath, resolved: false };
    }
    for (const [field, candidates] of [
      ['binary_sha256', ['.']],
      ['profile_sha256', ['runtime-connection']],
    ]) {
      const recorded = block[field];
      if (typeof recorded !== 'string') {
        problems.push(`${at}: ${field} is absent`);
        continue;
      }
      const matches = filesByDigest(root, recorded, candidates);
      if (matches.length === 0) problems.push(`${at}: no retained file under the evidence root hashes to ${field} ${recorded}`);
      row.digests.push({ field, resolved_by: matches });
    }
    runtimeEvidence.push(row);
  });

  connections.forEach((block, index) => {
    const at = `runtime_connections[${index}]`;
    if (block.class !== 'observed') problems.push(`${at}: class ${block.class} in the runtime connection list`);
    const paths = existingPaths(block);
    if (paths.length === 0) problems.push(`${at}: no existing evidence path`);
  });

  const ok = problems.length === 0;
  const summary = `${rows.length} graded blocks carry the fields their class requires; ${runtime.length} runtime observations and ${connections.length} connection observations reference retained evidence (trace statements, coverage rows, binary and profile digests recomputed)`;
  return {
    ok,
    detail: withProblems(summary, problems),
    evidence: { blocks: rows, runtime: runtimeEvidence },
  };
}

