async function catalogProvenance(root, options) {
  const planFile = path.join(root, 'catalog-plan.json');
  const plan = readJson(planFile);
  const database = path.join(root, 'runtime-connection/allowed.fossil');
  const sqlite = options.sqlite3 ?? DEFAULT_SQLITE3;
  const problems = [];
  const databaseBytes = readBytes(database);
  const digest = sha256Hex(databaseBytes);

  if (digest !== plan.database_sha256) {
    problems.push(`${database} hashes to ${digest}, catalog-plan.json records ${plan.database_sha256}`);
  }

  const argv = Array.isArray(plan.argv) ? plan.argv : [];
  if (!argv.includes(database)) problems.push(`catalog-plan.json argv does not name ${database}`);

  const fileFields = [];
  const openReads = [];
  const recordedCatalogRows = [];
  const results = Array.isArray(plan.results) ? plan.results : [];
  results.forEach((result, resultIndex) => {
    if (!Array.isArray(result)) return;
    result.forEach((row) => {
      if (row === null || typeof row !== 'object') return;
      if (typeof row.file === 'string') fileFields.push({ result: resultIndex, file: row.file });
      if (row.opcode === 'OpenRead') {
        openReads.push({ result: resultIndex, cursor: row.p1, rootpage: row.p2, comment: row.comment ?? null });
      }
      if (typeof row.rootpage === 'number' && typeof row.name === 'string' && typeof row.type === 'string') {
        recordedCatalogRows.push({ rootpage: row.rootpage, type: row.type, name: row.name, tbl_name: row.tbl_name ?? null });
      }
    });
  });

  for (const field of fileFields) {
    if (field.file !== database) problems.push(`catalog-plan.json results[${field.result}] names ${field.file} instead of ${database}`);
  }
  if (fileFields.length === 0) problems.push('catalog-plan.json records no database_list file entry');

  const sqliteVersion = runCapture(sqlite, ['--version']).stdout.trim();
  if (typeof plan.version === 'string' && plan.version !== sqliteVersion) {
    problems.push(`${sqlite} reports ${sqliteVersion} while catalog-plan.json records ${plan.version}`);
  }

  const query = 'SELECT type,name,tbl_name,rootpage FROM sqlite_schema ORDER BY rootpage';
  const live = runCapture(sqlite, ['-readonly', '-json', database, query]);
  if (live.status !== 0) throw new Error(`${sqlite} -readonly exits ${live.status}: ${live.stderr.trim()}`);
  const schemaRows = JSON.parse(live.stdout);

  const joined = [];
  for (const operand of openReads) {
    if (operand.rootpage === 0) {
      // Cursor 0 addresses the table itself; rootpage 0 is not a schema entry.
      joined.push({ ...operand, schema_rows: [], note: 'rootpage 0 addresses cursor 0 directly' });
      continue;
    }
    const matches = schemaRows.filter((row) => row.rootpage === operand.rootpage);
    if (matches.length !== 1) {
      problems.push(`OpenRead operand rootpage ${operand.rootpage} joins to ${matches.length} sqlite_schema rows`);
      joined.push({ ...operand, schema_rows: matches });
      continue;
    }
    const row = matches[0];
    const commentName = typeof operand.comment === 'string' ? operand.comment.split(';').pop().trim() : null;
    if (commentName !== null && commentName.length > 0 && commentName !== row.name && commentName !== row.tbl_name) {
      problems.push(
        `OpenRead operand rootpage ${operand.rootpage} comment names ${commentName} while the catalog row names ${row.name} (${row.type} ${row.tbl_name})`,
      );
    }
    joined.push({ ...operand, schema_rows: matches, name: row.name, type: row.type, tbl_name: row.tbl_name });
  }
  if (openReads.length === 0) problems.push('catalog-plan.json records no OpenRead operand');

  for (const recorded of recordedCatalogRows) {
    const live = schemaRows.find((row) => row.rootpage === recorded.rootpage);
    if (!live) {
      problems.push(`recorded catalog row rootpage ${recorded.rootpage} (${recorded.name}) is absent from the live catalog`);
      continue;
    }
    if (live.name !== recorded.name || live.type !== recorded.type) {
      problems.push(
        `recorded catalog row rootpage ${recorded.rootpage} is ${recorded.type} ${recorded.name} while the live catalog holds ${live.type} ${live.name}`,
      );
    }
  }

  const stats = statSync(database);
  const identity = {
    size: stats.size,
    inode: stats.ino,
    device: stats.dev,
    recorded_inode: plan.inode ?? null,
    recorded_device: plan.device ?? null,
    inode_matches: plan.inode === undefined || plan.inode === stats.ino,
    device_matches: plan.device === undefined || plan.device === stats.dev,
  };
  if (plan.inode !== undefined && plan.inode !== stats.ino) {
    problems.push(`catalog-plan.json records inode ${plan.inode} while ${database} has inode ${stats.ino}`);
  }

  const ok = problems.length === 0;
  const schemaByRoot = new Map(schemaRows.map((row) => [row.rootpage, `${row.type} ${row.name}`]));
  const summary = `${database} hashes to the recorded digest; ${fileFields.length} recorded file entries name it; ${openReads.length} OpenRead operands join to real sqlite_schema rows [${joined
    .map((entry) => `${entry.rootpage}=${schemaByRoot.get(entry.rootpage) ?? 'none'}`)
    .join(', ')}]; sqlite3 reports ${sqliteVersion}; inode ${stats.ino}`;
  return {
    ok,
    detail: withProblems(summary, problems),
    evidence: {
      plan: planFile,
      database,
      database_sha256: digest,
      recorded_database_sha256: plan.database_sha256,
      sqlite3: sqlite,
      sqlite3_version: sqliteVersion,
      recorded_version: plan.version ?? null,
      file_entries: fileFields,
      open_reads: openReads,
      joined_rows: joined,
      recorded_catalog_rows: recordedCatalogRows,
      live_schema_row_count: schemaRows.length,
      file_identity: identity,
    },
  };
}

// ---------------------------------------------------------------------------
// 5. guard-span
// ---------------------------------------------------------------------------

async function guardSpan(root) {
  const joined = readJson(path.join(root, 'joined-result.json'));
  const subject = joined.subject ?? {};
  const generatedPath = subject.source?.generated;
  if (typeof generatedPath !== 'string') throw new Error('joined-result.json subject.source.generated is absent');
  const bytes = readBytes(generatedPath);
  const relation = joined.security?.relation ?? {};
  const problems = [];

  const guard = relation.guard ?? {};
  const guardSpan = spanOf(guard.range);
  let guardText = null;
  if (!spanInBounds(bytes, guardSpan)) {
    problems.push(`security.relation.guard range ${JSON.stringify(guard.range)} does not index ${displayPath(root, generatedPath)} (${bytes.length} bytes)`);
  } else {
    guardText = spanText(bytes, guardSpan);
    const trimmed = guardText.trim();
    if (!/^if[\s(]/.test(trimmed)) problems.push(`security.relation.guard span does not start an if statement: ${JSON.stringify(trimmed.slice(0, 40))}`);
    const opens = (trimmed.match(/\{/g) ?? []).length;
    const closes = (trimmed.match(/\}/g) ?? []).length;
    if (opens === 0 || opens !== closes) problems.push(`security.relation.guard span does not hold a balanced block: {${opens} }${closes}`);
    if (!trimmed.endsWith('}')) problems.push(`security.relation.guard span does not end at a closing brace: ${JSON.stringify(trimmed.slice(-20))}`);
    if (guard.kind !== undefined && guard.kind !== 'IfStmt') problems.push(`security.relation.guard kind is ${guard.kind}`);
  }

  const fields = Array.isArray(relation.fields) ? relation.fields : [];
  if (fields.length < 2) problems.push(`security.relation.fields holds ${fields.length} entries; the guard records two operands`);
  const operands = [];
  const names = [];
  fields.forEach((field, index) => {
    const at = `security.relation.fields[${index}]`;
    const name = field.name;
    const expression = field.expression ?? {};
    const expressionSpan = spanOf(expression.range);
    if (typeof name !== 'string' || name.length === 0) {
      problems.push(`${at}: no operand name recorded`);
      return;
    }
    names.push(name);
    if (!spanInBounds(bytes, expressionSpan)) {
      problems.push(`${at}: expression range ${JSON.stringify(expression.range)} does not index ${displayPath(root, generatedPath)}`);
      return;
    }
    const endOffset = expression.range.end.offset;
    const endLength = expression.range.end.tokLen ?? 0;
    const nameToken = bytes.subarray(endOffset, endOffset + endLength).toString('utf8');
    if (nameToken !== name) {
      problems.push(`${at}: bytes at the recorded member offset ${endOffset} are ${JSON.stringify(nameToken)}, recorded name ${JSON.stringify(name)}`);
    }
    if (endOffset - 1 >= 0 && bytes[endOffset - 1] !== 0x2e) {
      problems.push(`${at}: byte before the member offset ${endOffset} is ${JSON.stringify(String.fromCharCode(bytes[endOffset - 1]))} instead of a dot`);
    }
    if (guardSpan !== null && (expressionSpan.start < guardSpan.start || expressionSpan.stop > guardSpan.stop)) {
      problems.push(`${at}: expression span ${expressionSpan.start}..${expressionSpan.stop} lies outside the guard span ${guardSpan.start}..${guardSpan.stop}`);
    }
    operands.push({
      name,
      expression_span: [expressionSpan.start, expressionSpan.stop],
      member_offset: endOffset,
      expression_text: spanText(bytes, expressionSpan),
    });
  });
  if (new Set(names).size !== names.length) problems.push(`security.relation.fields operand names repeat: ${names.join(', ')}`);

  const ok = problems.length === 0;
  const summary = `guard span ${guardSpan ? `${guardSpan.start}..${guardSpan.stop}` : 'absent'} spells ${JSON.stringify((guardText ?? '').trim())}; ${operands.length} field operands resolve to their recorded member names at offsets ${operands
    .map((operand) => `${operand.name}@${operand.member_offset}`)
    .join(', ')}; operand names are distinct`;
  return {
    ok,
    detail: withProblems(summary, problems),
    evidence: {
      generated: generatedPath,
      guard: { span: guardSpan ? [guardSpan.start, guardSpan.stop] : null, kind: guard.kind ?? null, text: guardText },
      operands,
    },
  };
}

// ---------------------------------------------------------------------------
// 6. relation-recompute
// ---------------------------------------------------------------------------

async function relationRecompute(root) {
  const cfgFile = path.join(root, 'compiler/view-list-cfg.txt');
  const text = readText(cfgFile);
  const blocks = parseCfg(text);
  const joined = readJson(path.join(root, 'joined-result.json'));
  const relation = joined.security?.relation ?? {};
  const problems = [];

  const entryBlocks = [...blocks.values()].filter((block) => block.label === 'ENTRY');
  if (entryBlocks.length !== 1) throw new Error(`${cfgFile}: ${entryBlocks.length} blocks carry the ENTRY label`);
  const entry = entryBlocks[0].id;
  const parsed = new Map([...blocks.values()].map((block) => [block.id, block.successors]));
  for (const block of blocks.values()) {
    if (block.declaredSuccessorCount !== null && block.declaredSuccessorCount !== block.successors.length) {
      problems.push(`block ${block.id}: Succs declares ${block.declaredSuccessorCount} successors and lists ${block.successors.length}`);
    }
  }

  // (b) the recorded successor map.
  const recorded = new Map();
  for (const [key, value] of Object.entries(relation.cfg_edges ?? {})) recorded.set(Number(key), value);
  const parsedIds = [...parsed.keys()].sort((a, b) => a - b);
  const recordedIds = [...recorded.keys()].sort((a, b) => a - b);
  if (parsedIds.length !== recordedIds.length || parsedIds.some((id, index) => id !== recordedIds[index])) {
    problems.push(`parsed block ids [${parsedIds.join(', ')}] differ from cfg_edges keys [${recordedIds.join(', ')}]`);
  }
  let successorMismatches = 0;
  for (const id of parsedIds) {
    if (!recorded.has(id)) continue;
    if (JSON.stringify(parsed.get(id)) !== JSON.stringify(recorded.get(id))) {
      successorMismatches += 1;
      problems.push(`block ${id}: parsed successors [${parsed.get(id).join(', ')}] differ from cfg_edges [${(recorded.get(id) ?? []).join(', ')}]`);
    }
  }

  // (a) forward reachability from the entry block.
  const entryReach = reachable(parsed, entry);
  const entryReachRecorded = reachable(recorded, entry);
  if (!sameNumberSet(entryReach, entryReachRecorded)) {
    problems.push(`entry reachability parsed [${entryReach.join(', ')}] differs from cfg_edges [${entryReachRecorded.join(', ')}]`);
  }

  // Accepted-state reachability: the accepted outcome of the guard continues in
  // the allow block, so the reachable set of the accepted state is computed from
  // that block, which is the quantity recorded as allow_reachable.
  const allowBlock = relation.allow_block;
  const denyBlock = relation.deny_block;
  const selectedCallBlock = relation.selected_call_block;
  if (!parsed.has(allowBlock)) problems.push(`allow_block ${allowBlock} is not a parsed block`);
  if (!parsed.has(denyBlock)) problems.push(`deny_block ${denyBlock} is not a parsed block`);
  const acceptedStateReach = parsed.has(allowBlock) ? reachable(parsed, allowBlock) : [];
  if (!sameNumberSet(acceptedStateReach, relation.allow_reachable)) {
    problems.push(`accepted-state reachability from the allow block [${acceptedStateReach.join(', ')}] differs from allow_reachable [${(relation.allow_reachable ?? []).join(', ')}]`);
  }
  if (selectedCallBlock !== undefined && !acceptedStateReach.includes(selectedCallBlock)) {
    problems.push(`selected_call_block ${selectedCallBlock} is not reachable from the allow block ${allowBlock}`);
  }
  if (denyBlock !== undefined && !entryReach.includes(denyBlock)) {
    problems.push(`deny_block ${denyBlock} is not reachable from the entry block ${entry}`);
  }

  // (c) the accepted exit-edge set: the false successor edges of the
  // short-circuit decision blocks that feed the allow block. LLVM emits the
  // true successor first and the false successor second.
  const decisionBlocks = [...blocks.values()].filter((block) => block.hasConditionalTerminator && block.successors.includes(allowBlock));
  const acceptedEdges = new Set();
  for (const block of decisionBlocks) {
    const index = block.successors.indexOf(allowBlock);
    if (index === 1) acceptedEdges.add(`${block.id}->${allowBlock}`);
    else problems.push(`block ${block.id}: the allow block ${allowBlock} is successor index ${index}; the false successor sits at index 1`);
  }
  if (decisionBlocks.length === 0) problems.push(`no conditional block feeds the allow block ${allowBlock}`);
  if (acceptedEdges.size === 0) problems.push('the accepted exit-edge set is empty');

  // (d) reachability after removing the whole accepted exit-edge set.
  const trimmed = new Map([...parsed.entries()].map(([id, successors]) => [id, [...successors]]));
  const reachWithoutAccepted = reachable(trimmed, entry, acceptedEdges);
  if (!sameNumberSet(reachWithoutAccepted, relation.entry_reach_with_allow_block_removed)) {
    problems.push(
      `reachability after removing ${[...acceptedEdges].join(', ')} is [${reachWithoutAccepted.join(', ')}] and entry_reach_with_allow_block_removed holds [${(relation.entry_reach_with_allow_block_removed ?? []).join(', ')}]`,
    );
  }

  // (e) the selected call block is unreachable once the accepted edges are gone.
  const callReachable = reachWithoutAccepted.includes(selectedCallBlock);
  if (callReachable) problems.push(`selected_call_block ${selectedCallBlock} stays reachable after removing the accepted exit edges`);
  if (relation.selected_unreachable_when_allow_block_removed !== !callReachable) {
    problems.push(
      `selected_unreachable_when_allow_block_removed is ${relation.selected_unreachable_when_allow_block_removed} while the recomputed value is ${!callReachable}`,
    );
  }
  if (!callReachable === false) problems.push('the selected call block is reachable in the recomputed graph');

  // (f) the deny block is reachable from the entry through no accepted edge and
  // its text holds a return terminator.
  const denyReachWithoutAccepted = reachable(parsed, entry, acceptedEdges);
  if (!denyReachWithoutAccepted.includes(denyBlock)) {
    problems.push(`deny_block ${denyBlock} is unreachable from the entry block ${entry} without an accepted edge`);
  }
  const denyText = parsed.has(denyBlock) ? blocks.get(denyBlock).body.join('\n') : '';
  if (!denyText.includes('return;')) problems.push(`deny_block ${denyBlock} holds no return; terminator`);
  const denyReach = parsed.has(denyBlock) ? reachable(parsed, denyBlock) : [];
  if (!sameNumberSet(denyReach, relation.deny_reachable)) {
    problems.push(`deny_block reachability [${denyReach.join(', ')}] differs from deny_reachable [${(relation.deny_reachable ?? []).join(', ')}]`);
  }
  if (relation.class !== 'static-possible') problems.push(`security.relation class is ${relation.class}`);

  const ok = problems.length === 0;
  const summary = `${blocks.size} blocks parsed with ordered successors ${successorMismatches === 0 ? 'matching' : 'differing from'} cfg_edges; entry block ${entry} reaches [${entryReach.join(', ')}]; accepted exit edges ${[...acceptedEdges].sort().join(', ')}; reachability after their removal [${reachWithoutAccepted.join(', ')}]; selected call block ${selectedCallBlock} unreachable in that graph and selected_unreachable_when_allow_block_removed is ${relation.selected_unreachable_when_allow_block_removed}; deny block ${denyBlock} reachable through no accepted edge with a return terminator`;
  return {
    ok,
    detail: withProblems(summary, problems),
    evidence: {
      cfg: cfgFile,
      entry_block: entry,
      block_count: blocks.size,
      accepted_edges: [...acceptedEdges].sort(),
      decision_blocks: decisionBlocks.map((block) => block.id),
      entry_reachable: entryReach,
      accepted_state_reachable: acceptedStateReach,
      reach_without_accepted_edges: reachWithoutAccepted,
      deny_reachable: denyReach,
      deny_block_text: denyText.trim().split('\n').filter((line) => line.trim().length > 0),
      selected_call_block: selectedCallBlock ?? null,
    },
  };
}

// ---------------------------------------------------------------------------
// 7. same-handler-families
// ---------------------------------------------------------------------------

async function sameHandlerFamilies(root) {
  const joined = readJson(path.join(root, 'joined-result.json'));
  const problems = [];
  const subject = joined.subject;
  if (Array.isArray(subject) || subject === null || typeof subject !== 'object') {
    problems.push('joined-result.json subject is not a single object');
  }
  for (const key of ['subjects', 'handlers', 'results']) {
    if (Array.isArray(joined[key])) problems.push(`joined-result.json carries a ${key} array next to subject`);
  }
  const functionName = subject && typeof subject.function === 'string' ? subject.function : null;
  if (functionName === null) problems.push('subject.function is absent');

  const families = ['types', 'calls', 'security', 'database', 'diagnostics'];
  const familyRows = [];
  for (const name of families) {
    const family = joined[name];
    if (family === null || typeof family !== 'object' || Array.isArray(family)) {
      problems.push(`family ${name} is absent from joined-result.json`);
      continue;
    }
    if (typeof family.class !== 'string') problems.push(`family ${name} carries no class`);
    let size = 0;
    if (name === 'types') size = (family.global_inputs?.length ?? 0) + (family.handler_type ? 1 : 0);
    if (name === 'calls') size = family.facts?.length ?? 0;
    if (name === 'security') size = (family.roles ? 1 : 0) + (family.relation ? 1 : 0);
    if (name === 'database') size = family.sql ? 1 : 0;
    if (name === 'diagnostics') size = family.files?.length ?? 0;
    if (size === 0) problems.push(`family ${name} carries no entries for the subject`);
    familyRows.push({ name, class: family.class, entries: size });
  }

  const generatedPath = subject?.source?.generated;
  const generatedBytes = typeof generatedPath === 'string' ? readBytes(generatedPath) : null;
  const subjectSpan = Array.isArray(subject?.source?.generated_byte_span)
    ? { start: subject.source.generated_byte_span[0], stop: subject.source.generated_byte_span[1] }
    : null;

  // Handler-body facts must index the recorded subject bytes.
  const bodySpans = [];
  for (const [index, fact] of (joined.calls?.facts ?? []).entries()) {
    bodySpans.push({ at: `calls.facts[${index}].call`, span: spanOf(fact.call?.range) });
  }
  bodySpans.push({ at: 'security.relation.guard', span: spanOf(joined.security?.relation?.guard?.range) });
  (joined.security?.relation?.fields ?? []).forEach((field, index) => {
    bodySpans.push({ at: `security.relation.fields[${index}].expression`, span: spanOf(field.expression?.range) });
  });
  for (const name of ['selected_prepare', 'selected_step', 'literal']) {
    bodySpans.push({ at: `database.${name}`, span: spanOf(joined.database?.[name]?.range) });
  }
  const outside = [];
  for (const entry of bodySpans) {
    if (generatedBytes === null) break;
    if (!spanInBounds(generatedBytes, entry.span)) {
      outside.push(`${entry.at} range ${JSON.stringify(entry.span)} is outside ${generatedBytes.length} bytes`);
      continue;
    }
    if (subjectSpan !== null && spanInBounds(generatedBytes, subjectSpan) && (entry.span.start < subjectSpan.start || entry.span.stop > subjectSpan.stop)) {
      outside.push(`${entry.at} range ${entry.span.start}..${entry.span.stop} lies outside the subject span ${subjectSpan.start}..${subjectSpan.stop}`);
    }
  }
  problems.push(...outside);

  // The selected-db_prepare signature gate.
  const types = joined.types ?? {};
  const parameters = types.parameters;
  if (!Array.isArray(parameters)) problems.push('types.parameters is not an array');
  else if (parameters.length !== 0) problems.push(`types.parameters holds ${parameters.length} formals for the selected handler`);
  const example = types.nonempty_parameter_example ?? {};
  const exampleParameters = example.parameters;
  if (!Array.isArray(exampleParameters) || exampleParameters.length === 0) {
    problems.push('types.nonempty_parameter_example.parameters is empty');
  } else {
    exampleParameters.forEach((parameter, index) => {
      if (typeof parameter.name !== 'string' || parameter.name.length === 0) {
        problems.push(`types.nonempty_parameter_example.parameters[${index}] carries no name`);
      }
      if (typeof parameter.type?.qualType !== 'string' || parameter.type.qualType.length === 0) {
        problems.push(`types.nonempty_parameter_example.parameters[${index}] carries no qualType`);
      }
    });
  }
  if (typeof example.name !== 'string' || example.name.length === 0) problems.push('types.nonempty_parameter_example.name is absent');
  if (example.name !== undefined && example.name === functionName) {
    problems.push(`types.nonempty_parameter_example.name ${example.name} equals the selected function name`);
  }

  const ok = problems.length === 0;
  const summary = `subject ${JSON.stringify(functionName)} carries families ${familyRows
    .map((row) => `${row.name}(${row.class}, ${row.entries})`)
    .join(', ')}; ${bodySpans.length} handler-body ranges index the subject span ${subjectSpan ? `${subjectSpan.start}..${subjectSpan.stop}` : 'absent'}; types.parameters is empty while nonempty_parameter_example ${JSON.stringify(example.name)} holds ${exampleParameters?.length ?? 0} formals`;
  return {
    ok,
    detail: withProblems(summary, problems),
    evidence: {
      subject: subject ?? null,
      families: familyRows,
      body_range_count: bodySpans.length,
      body_range_failures: outside,
      handler_type: types.handler_type ?? null,
      parameters: parameters ?? null,
      nonempty_parameter_example: { name: example.name ?? null, parameters: exampleParameters ?? null },
    },
  };
}

// ---------------------------------------------------------------------------
// 8. database-join
// ---------------------------------------------------------------------------

async function databaseJoin(root) {
  const joined = readJson(path.join(root, 'joined-result.json'));
  const subject = joined.subject ?? {};
  const generatedPath = subject.source?.generated;
  if (typeof generatedPath !== 'string') throw new Error('joined-result.json subject.source.generated is absent');
  const bytes = readBytes(generatedPath);
  const database = joined.database ?? {};
  const problems = [];

  const sql = database.sql;
  if (typeof sql !== 'string') throw new Error('database.sql is absent');
  const literalSpan = spanOf(database.literal?.range);
  let literalText = null;
  if (!spanInBounds(bytes, literalSpan)) {
    problems.push(`database.literal range ${JSON.stringify(database.literal?.range)} does not index ${displayPath(root, generatedPath)}`);
  } else {
    literalText = spanText(bytes, literalSpan);
    const quoted = `"${sql}"`;
    if (literalText !== quoted) {
      problems.push(`database.sql ${JSON.stringify(sql)} differs from the literal span bytes ${JSON.stringify(literalText)}`);
    }
    if (database.literal?.kind !== undefined && database.literal.kind !== 'StringLiteral') {
      problems.push(`database.literal kind is ${database.literal.kind}`);
    }
    const byteLength = Buffer.byteLength(sql, 'utf8');
    if (literalSpan.stop - literalSpan.start !== byteLength + 2) {
      problems.push(`the literal span covers ${literalSpan.stop - literalSpan.start} bytes for a ${byteLength}-byte statement`);
    }
  }

  // The selected prepare call names a helper recorded in the summary bindings.
  const prepareSpan = spanOf(database.selected_prepare?.range);
  const bindings = Array.isArray(database.helper_summary?.bindings) ? database.helper_summary.bindings : [];
  let callee = null;
  let binding = null;
  if (!spanInBounds(bytes, prepareSpan)) {
    problems.push(`database.selected_prepare range ${JSON.stringify(database.selected_prepare?.range)} does not index ${displayPath(root, generatedPath)}`);
  } else {
    const calleeLength = database.selected_prepare.range.begin.tokLen ?? 0;
    callee = bytes.subarray(prepareSpan.start, prepareSpan.start + calleeLength).toString('utf8');
    binding = bindings.find((entry) => entry.name === callee) ?? null;
    if (binding === null) {
      problems.push(`database.selected_prepare names callee ${JSON.stringify(callee)}, which no helper_summary binding records`);
    }
    if (literalSpan !== null && spanInBounds(bytes, literalSpan) && (literalSpan.start < prepareSpan.start || literalSpan.stop > prepareSpan.stop)) {
      problems.push(`the SQL literal span ${literalSpan.start}..${literalSpan.stop} lies outside the prepare call span ${prepareSpan.start}..${prepareSpan.stop}`);
    }
    const callText = spanText(bytes, prepareSpan);
    const recomputedArguments = countCallArguments(callText);
    if (recomputedArguments !== null && recomputedArguments !== database.actual_argument_count) {
      problems.push(`database.actual_argument_count is ${database.actual_argument_count} while the call text holds ${recomputedArguments} arguments`);
    }
  }

  // Preparation and the first step resolve the same local declaration.
  const statementVariable = database.statement_variable ?? {};
  const stepDeclaration = database.step_same_decl ?? {};
  if (statementVariable.id === undefined || stepDeclaration.id === undefined) {
    problems.push('database.statement_variable or database.step_same_decl carries no declaration id');
  } else if (statementVariable.id !== stepDeclaration.id) {
    problems.push(`statement_variable ${statementVariable.id} differs from step_same_decl ${stepDeclaration.id}`);
  }
  if (statementVariable.name !== stepDeclaration.name || statementVariable.kind !== stepDeclaration.kind) {
    problems.push(
      `statement_variable ${statementVariable.kind} ${statementVariable.name} differs from step_same_decl ${stepDeclaration.kind} ${stepDeclaration.name}`,
    );
  }

  // The literal holds no percent and no NUL byte.
  const hasPercent = sql.includes('%');
  const hasNul = sql.includes('\u0000') || (literalText !== null && literalText.includes('\u0000'));
  if (database.no_format_no_nul !== (!hasPercent && !hasNul)) {
    problems.push(`database.no_format_no_nul is ${database.no_format_no_nul} while the statement holds percent=${hasPercent} nul=${hasNul}`);
  }

  // Target and planner versions are distinct, and each is independently known.
  const targetVersion = database.target_sqlite_source_version;
  const plannerVersion = database.external_planner_version;
  if (typeof targetVersion !== 'string' || typeof plannerVersion !== 'string') {
    problems.push('database.target_sqlite_source_version or database.external_planner_version is absent');
  } else if (targetVersion === plannerVersion) {
    problems.push('database target and external planner versions are equal');
  }
  const headerFile = path.join(root, 'source/fossil/src/sqlite3.h');
  if (existsSync(headerFile)) {
    const header = readText(headerFile);
    const define = /#define\s+SQLITE_VERSION\s+"([^"]+)"/.exec(header);
    if (decline(define)) problems.push(`${displayPath(root, headerFile)} records no SQLITE_VERSION define`);
    else if (define[1] !== targetVersion) {
      problems.push(`source/sqlite3.h defines SQLITE_VERSION ${define[1]} while database.target_sqlite_source_version is ${targetVersion}`);
    }
  } else {
    problems.push(`${displayPath(root, headerFile)} is absent; the target version cannot be recomputed`);
  }
  const sqlite = options0Sqlite(root);
  const livePlanner = runCapture(sqlite, ['--version']).stdout.trim();
  if (livePlanner !== plannerVersion) {
    problems.push(`${sqlite} reports ${livePlanner} while database.external_planner_version is ${plannerVersion}`);
  }

  const catalogEvidence = database.catalog_evidence;
  if (typeof catalogEvidence !== 'string' || !existsSync(catalogEvidence)) {
    problems.push(`database.catalog_evidence ${JSON.stringify(catalogEvidence)} is not a retained file`);
  }

  const ok = problems.length === 0;
  const summary = `database.sql equals the literal span bytes at ${literalSpan ? `${literalSpan.start}..${literalSpan.stop}` : 'absent'}; the prepare call ${JSON.stringify(callee)} is recorded in helper_summary.bindings; statement_variable and step_same_decl share ${statementVariable.id ?? 'no id'}; no_format_no_nul recomputes to ${!hasPercent && !hasNul}; target ${targetVersion} differs from planner ${plannerVersion}`;
  return {
    ok,
    detail: withProblems(summary, problems),
    evidence: {
      generated: generatedPath,
      sql,
      literal_text: literalText,
      literal_span: literalSpan ? [literalSpan.start, literalSpan.stop] : null,
      prepare_span: prepareSpan ? [prepareSpan.start, prepareSpan.stop] : null,
      callee,
      binding_name: binding?.name ?? null,
      binding_mangled: binding?.mangledName ?? null,
      argument_count: database.actual_argument_count,
      statement_variable: statementVariable,
      step_same_decl: stepDeclaration,
      no_format_no_nul: { recorded: database.no_format_no_nul, percent: hasPercent, nul: hasNul },
      target_sqlite_source_version: targetVersion ?? null,
      external_planner_version: plannerVersion ?? null,
      live_planner_version: livePlanner,
      catalog_evidence: catalogEvidence ?? null,
    },
  };
}

