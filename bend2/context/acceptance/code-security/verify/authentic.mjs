// ---------------------------------------------------------------------------

async function noEnforcementClaim(root) {
  const joinedFile = path.join(root, 'joined-result.json');
  const joined = readJson(joinedFile);
  const problems = [];
  const hits = [];
  for (const { at, text } of collectStrings(joined)) {
    for (const claim of enforcementClaims(text)) hits.push({ at, claim });
  }
  if (hits.length > 0) {
    for (const hit of hits.slice(0, 12)) problems.push(`${hit.at}: ${hit.claim}`);
    if (hits.length > 12) problems.push(`${hits.length - 12} more assertion clauses`);
  }

  const limits = [
    { at: 'security.relation.limits', values: joined.security?.relation?.limits },
    { at: 'runtime[0].limits', values: joined.runtime?.[0]?.limits },
    { at: 'runtime[1].limits', values: joined.runtime?.[1]?.limits },
  ];
  for (const entry of limits) {
    if (!Array.isArray(entry.values) || entry.values.length === 0) {
      problems.push(`${entry.at} holds no limit entries`);
      continue;
    }
    for (const value of entry.values) {
      if (typeof value !== 'string' || value.trim().length === 0) problems.push(`${entry.at} holds a non-string limit entry`);
    }
  }

  const ok = problems.length === 0;
  const limitReport = limits
    .map((entry) => `${entry.at}: ${Array.isArray(entry.values) ? entry.values.map((value) => JSON.stringify(value)).join('; ') : 'absent'}`)
    .join(' || ');
  const summary = `no string asserts guard enforcement, principal authenticity or effect completion; limits present ${limitReport}`;
  return {
    ok,
    detail: withProblems(summary, problems),
    evidence: {
      limits: limits.map((entry) => ({ at: entry.at, values: entry.values ?? null })),
      assertions: hits,
    },
  };
}

